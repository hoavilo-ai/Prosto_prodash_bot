"""
Генерация черновиков текста (ответы лидам в личке + посты в канал) через
Anthropic API. Бот НИКОГДА не отправляет и не публикует результат этого
модуля напрямую — черновик всегда уходит админу (Николаю) на подтверждение
через bot.py, этот модуль только готовит текст.

Требует переменную окружения ANTHROPIC_API_KEY (ключ из console.anthropic.com,
раздел API Keys — это отдельный ключ, не связанный с обычной подпиской на
Claude.ai и Claude Code, оплачивается отдельно по использованию).

Экспортирует:
  draft_reply_to_lead(user_text, user_name) -> str
  draft_channel_post(brief) -> str
  revise_draft(previous_draft, instruction, kind) -> str
  AIDraftError — поднимается вместо падения, если ключа нет или API вернул ошибку
"""

import os

from anthropic import Anthropic, APIError

ANTHROPIC_API_KEY = os.environ.get("ANTHROPIC_API_KEY")
# Можно переопределить переменной окружения ANTHROPIC_MODEL, если понадобится
# другая модель — менять код для этого не нужно.
MODEL = os.environ.get("ANTHROPIC_MODEL", "claude-sonnet-4-5-20250929")


class AIDraftError(Exception):
    """Понятная ошибка для показа админу вместо падения бота."""


# ------------------------------------------------------------------------
# Голос Николая + стиль канала — единственное место, где это описано.
# Чтобы поправить тон черновиков, редактируйте только эти две константы.
# ------------------------------------------------------------------------

PERSONA_SYSTEM = """Ты помогаешь Николаю Хоавило — тренеру по продажам и переговорам \
(15 лет в продажах, из них 12 лет в нише автомобильных смазочных материалов: \
Motul, Shell, Sintec Group) — готовить черновики текста. Ты пишешь ЗА НЕГО, от \
первого лица, как будто это сам Николай. Черновик ВСЕГДА проверяет и \
подтверждает сам Николай перед отправкой или публикацией — твоя задача дать \
вариант, максимально близкий к его голосу, а не финальный идеальный текст.

Стиль Николая:
- прямой, разговорный, без канцелярита и штампов из учебников по продажам
- короткие абзацы (1-3 предложения)
- конкретика и примеры из практики, а не общие советы "в воздух"
- никогда не использовать длинное тире (—) — только обычный дефис (-)
- один-два emoji, не больше, и не в каждом предложении
- НИКОГДА не выдумывай цифры, кейсы, имена, даты или факты, которых нет в \
предоставленном тексте — если конкретики не хватает, пиши короче и общее, \
без придуманных деталей"""

CHANNEL_STYLE_BRIEF = """Стиль канала t.me/prosto_prodash (по уже опубликованным постам):
- короткие посты: 3-5 коротких абзацев
- часто начинаются с заголовка-категории в одну строку ("Ошибка менеджеров", \
"Ошибка руководителей", "Кейс с клиентом", "Личный опыт", "Работа \
руководителей" и т.п.), затем пустая строка и текст
- структура: конкретная ситуация или наблюдение -> в чём ошибка или урок -> \
короткий практический вывод в конце, часто в повелительном наклонении \
("Поменяйте...", "Проверьте...", "Не упустите...")
- без воды и лозунгов, по возможности с конкретными деталями ситуации
- кейсы даются без названий компаний, но с конкретным результатом, если он есть
- заканчивается обычно одним emoji к месту (например 🔥 🫡 💪🏽 🤘🏼 📈), а не \
смайликом на каждую строку"""


def _client() -> Anthropic:
    if not ANTHROPIC_API_KEY:
        raise AIDraftError(
            "Не задана переменная окружения ANTHROPIC_API_KEY — без неё "
            "бот не может сгенерировать черновик."
        )
    return Anthropic(api_key=ANTHROPIC_API_KEY)


def _complete(system: str, user: str, max_tokens: int = 600) -> str:
    client = _client()
    try:
        response = client.messages.create(
            model=MODEL,
            max_tokens=max_tokens,
            system=system,
            messages=[{"role": "user", "content": user}],
        )
    except APIError as exc:
        raise AIDraftError(f"Anthropic API вернул ошибку: {exc}") from exc
    except Exception as exc:  # сетевые и прочие неожиданные сбои
        raise AIDraftError(f"Не удалось обратиться к Anthropic API: {exc}") from exc

    text_parts = [
        block.text for block in response.content if getattr(block, "type", None) == "text"
    ]
    draft = "".join(text_parts).strip()
    if not draft:
        raise AIDraftError("Anthropic API вернул пустой ответ.")
    return draft


def draft_reply_to_lead(user_text: str, user_name: str) -> str:
    """Черновик ответа человеку, который написал боту в личку."""
    system = (
        PERSONA_SYSTEM
        + "\n\nТы отвечаешь на личное сообщение в Telegram, которое человек "
        "написал Николаю (это может быть лид, подписчик канала или клиент)."
    )
    user = (
        f'Сообщение от {user_name}:\n"""\n{user_text}\n"""\n\n'
        "Напиши короткий черновик ответа (2-5 предложений), по делу, в стиле "
        "Николая. Если вопрос требует конкретики, которой у тебя нет (точные "
        "цены, даты, детали программы тренинга под конкретного заказчика) - "
        "не выдумывай, а предложи обсудить детали лично или созвониться."
    )
    return _complete(system, user, max_tokens=400)


def draft_channel_post(brief: str) -> str:
    """Черновик нового поста в канал по теме/брифу от Николая."""
    system = (
        PERSONA_SYSTEM
        + "\n\n"
        + CHANNEL_STYLE_BRIEF
        + "\n\nТы готовишь черновик НОВОГО поста для канала по теме/брифу от Николая."
    )
    user = (
        f'Тема или бриф поста:\n"""\n{brief}\n"""\n\n'
        "Напиши черновик поста в стиле канала (см. выше). Если бриф не "
        "содержит конкретных деталей кейса (цифр, цитат клиента) - не "
        "выдумывай их: сделай пост более общим, на уровне наблюдения или "
        "принципа, а не вымышленного кейса."
    )
    return _complete(system, user, max_tokens=700)


def revise_draft(previous_draft: str, instruction: str, kind: str) -> str:
    """Переписывает черновик с учётом правки Николая.

    kind: "reply" (ответ лиду) или "post" (пост в канал) — влияет только на
    то, подключать ли CHANNEL_STYLE_BRIEF.
    """
    context_label = "ответа лиду" if kind == "reply" else "поста в канал"
    system = PERSONA_SYSTEM + ("\n\n" + CHANNEL_STYLE_BRIEF if kind == "post" else "")
    user = (
        f'Вот черновик {context_label}, который нужно доработать:\n"""\n'
        f'{previous_draft}\n"""\n\n'
        f'Правка от Николая: "{instruction}"\n\n'
        "Перепиши черновик целиком с учётом этой правки. Верни только новый "
        "текст, без пояснений от себя."
    )
    return _complete(system, user, max_tokens=700)
